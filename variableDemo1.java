public class variableDemo1{
    //主入口
    public static void main(String[] args){
        //定义变量
        //数据类型 变量名 = 数据值
        //int(整数),double(小数)
        //变量名: 就是存储空间的名字
        //作用:方便以后使用
        //数据值:真正存在变量中的数据
        int a = 10, b = 20, c = 30;
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
    }
}
